/**
 * scripts/export-asset-index.ts
 *
 * Converts assets.catalog.json (node-side, fs-based) into a bundled TS module
 * (src/compositions/assetIndex.generated.ts) with pre-filtered buckets, so the
 * 3D stage components can pick street/crowd/vehicle models at render time
 * without touching node fs (compositions run in the browser).
 *
 * Usage: npm run assets:index   (auto-rerun after npm run assets)
 */
import fs from "fs";
import path from "path";

const ROOT = path.join(__dirname, "..");
const CATALOG = path.join(ROOT, "assets.catalog.json");
const OUT = path.join(ROOT, "src", "compositions", "assetIndex.generated.ts");

interface CatalogEntry {
  id: string;
  file: string;
  pack: string;
  category: string;
  tags: string[];
  animations: string[];
  license: string;
}

interface IndexedAsset {
  id: string;
  file: string;
  pack: string;
  animations: string[];
}

const is = (set: IndexedAsset[], e: CatalogEntry): boolean => set.some((m) => m.id === e.id);

function main(): void {
  if (!fs.existsSync(CATALOG)) {
    console.error(
      "[assets:index] assets.catalog.json is missing — run \"npm run assets\" first to download the CC0 model packs, then retry.",
    );
    process.exit(1);
  }
  const raw = fs.readFileSync(CATALOG, "utf8");
  const catalog = JSON.parse(raw) as { assets: CatalogEntry[] };
  const entries = catalog.assets ?? [];
  console.log(`[assets:index] catalog has ${entries.length} models`);

  const compact = (e: CatalogEntry): IndexedAsset => ({ id: e.id, file: e.file, pack: e.pack, animations: e.animations });

  const personTag = (e: CatalogEntry): boolean =>
    e.category === "characters" && /\b(person|man|woman|female|male|pedestrian)\b|human/.test(e.tags.join(" "));

  const buildings = entries.filter((e) =>
    (e.pack === "city-kit-commercial" || e.pack === "city-kit-suburban") &&
    /building/.test(e.id),
  );
  const cityDetails = entries.filter((e) =>
    (e.pack === "city-kit-commercial" || e.pack === "city-kit-suburban") &&
    /(awning|parasol|overhang)/.test(e.id),
  );
  const roadProps = entries.filter((e) => e.pack === "city-kit-roads");
  const humansAnimated = entries.filter((e) => personTag(e) && e.animations.length > 0);
  const humansBlocky = entries.filter((e) =>
    (e.pack === "blocky-characters" || e.pack === "mini-characters" || (e.pack === "polypizza" && personTag(e))) &&
    personTag(e) && !buildings.some((b) => b.id === e.id),
  );
  const pets = entries.filter((e) => e.category === "characters" && /(shiba|husky|dog|sheep|goat)/.test(e.id));
  const vehicles = entries.filter((e) => e.category === "vehicles");
  const natureTrees = entries.filter((e) => e.category === "nature" && /(tree|oak|pine|fir|palm|birch)/.test(e.id));
  const natureShrubs = entries.filter((e) => e.category === "nature" && !is(natureTrees, e) &&
    /(bush|shrub|plant|topiary|planter|pot|flower|grass|fern)/.test(e.id));
  const seating = entries.filter((e) =>
    (e.pack === "furniture-kit" || e.pack === "food-kit" || e.category === "props") &&
    /(chair|table|stool|parasol|umbrella|bench)/.test(e.id),
  );
  const streetProps = entries.filter((e) =>
    e.category === "props" && !is(seating, e) &&
    /(lamp|bench|trash|garbage|hydrant|mailbox|sign|post|bin|cone|crate|bag|paper|box)/.test(e.id),
  );

  const buckets: Record<string, IndexedAsset[]> = {
    CITY_BUILDINGS: buildings.map(compact),
    CITY_DETAILS: cityDetails.map(compact),
    ROAD_PROPS: roadProps.map(compact),
    HUMANS_ANIMATED: humansAnimated.map(compact),
    HUMANS_ANY: humansBlocky.map(compact),
    PETS: pets.map(compact),
    VEHICLES: vehicles.map(compact),
    NATURE_TREES: natureTrees.map(compact),
    NATURE_SHRUBS: natureShrubs.map(compact),
    SEATING: seating.map(compact),
    PROPS_STREET: streetProps.map(compact),
  };

  const head = `/**
 * assetIndex.generated.ts — auto-generated by scripts/export-asset-index.ts.
 * DO NOT EDIT BY HAND. Rerun with "npm run assets" (or "npm run assets:index").
 * Buckets feed the 3D street stage (StreetStage.tsx) so it can dress the
 * world from whatever models are installed.
 */
export interface IndexedAsset {
  id: string;
  /** path relative to public/ — use with staticFile() */
  file: string;
  pack: string;
  animations: string[];
}
`;

  const body = Object.entries(buckets)
    .map(([name, list]) => {
      if (list.length === 0) return `export const ${name}: IndexedAsset[] = [];`;
      const items = list
        .map((m) => `  { id: ${JSON.stringify(m.id)}, file: ${JSON.stringify(m.file)}, pack: ${JSON.stringify(m.pack)}, animations: ${JSON.stringify(m.animations)} },`)
        .join("\n");
      return `export const ${name}: IndexedAsset[] = [\n${items}\n];`;
    })
    .join("\n\n");

  fs.writeFileSync(OUT, `${head}\n${body}\n`);
  console.log(
    `[assets:index] buckets → ${Object.entries(buckets)
      .map(([n, l]) => `${n}:${l.length}`)
      .join(" ")}\n[assets:index] written → src/compositions/assetIndex.generated.ts`,
  );
  if (humansAnimated.length === 0) {
    console.warn('[assets:index] WARNING: no animated human models found — the walking crowd falls back to static characters. Run "npm run assets" to fetch the Quaternius people packs.');
  }
}

main();
